import { existsSync, writeFileSync, readdirSync, readFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { runHook, root, OP_FILE_RE } from './lib.mjs';

runHook('op-scaffold', 'PostFileCreate', (ev) => {
  const file = ev.file_path ? resolve(ev.cwd ?? root(), ev.file_path) : '';
  if (!OP_FILE_RE.test(file.replace(/\\/g, '/'))) return { result: 'pass', target: file || null, detail: 'not an op file' };
  const dir = dirname(file);
  const name = basename(file, '.op.ts');
  const props = join(dir, `${name}.props.test.ts`);
  const did = [];
  if (!existsSync(props)) {
    let rel = relative(dir, join(root(), 'kit', 'props', 'run.ts')).replace(/\\/g, '/').replace(/\.ts$/, '.ts');
    if (!rel.startsWith('.')) rel = `./${rel}`;
    writeFileSync(
      props,
      `import def from './${name}.op.ts';\nimport { runOpProperties } from '${rel}';\n\nrunOpProperties(def);\n`,
    );
    did.push(`${name}.props.test.ts`);
  }
  const ops = readdirSync(dir).filter((f) => f.endsWith('.op.ts')).sort();
  const ident = (f) => f.replace(/\.op\.ts$/, '').replace(/[^A-Za-z0-9_$]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')).replace(/^(\d)/, '_$1');
  const body =
    '// generated by kit/hooks/op-scaffold.mjs — do not edit\n' +
    ops.map((f) => `import ${ident(f)} from './${f}';`).join('\n') +
    (ops.length ? '\n\n' : '\n') +
    `export const ops = [${ops.map((f) => ident(f)).join(', ')}];\n`;
  const reg = join(dir, 'registry.gen.ts');
  if (!existsSync(reg) || readFileSync(reg, 'utf8') !== body) {
    writeFileSync(reg, body);
    did.push('registry.gen.ts');
  }
  return { result: did.length ? 'scaffolded' : 'pass', target: file, detail: did.join(',') || 'nothing to do' };
});
